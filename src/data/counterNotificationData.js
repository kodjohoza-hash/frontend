const now = new Date();
const day = (offset) => {
  const d = new Date(now);
  d.setDate(d.getDate() - offset);
  d.setHours(8 + Math.floor(Math.random() * 12), Math.floor(Math.random() * 60), 0, 0);
  return d;
};
const iso = (offset) => day(offset).toISOString();
const isoOffset = (offset, h, m) => {
  const d = new Date(now);
  d.setDate(d.getDate() - offset);
  d.setHours(h ?? 8 + Math.floor(Math.random() * 12), m ?? Math.floor(Math.random() * 60), 0, 0);
  return d.toISOString();
};

const dateStr = (offset) => {
  const d = day(offset);
  return d.toLocaleDateString('fr-CM', { year: 'numeric', month: 'long', day: 'numeric' });
};

