const priorityRank = { critical: 0, high: 1, normal: 2, low: 3 };

export function filterNotifications(notifs, filters = {}) {
  const {
    search = '',
    category = 'all',
    priority = 'all',
    status = 'all',
    dateFrom = null,
    dateTo = null,
    clientName = '',
    tripRef = '',
    busRef = '',
    bookingRef = '',
    paymentRef = '',
    branchRef = '',
  } = filters;

  return notifs.filter((n) => {
    if (search) {
      const q = search.toLowerCase();
      const inTitle = n.title.toLowerCase().includes(q);
      const inDesc = n.description.toLowerCase().includes(q);
      const inFull = n.fullDescription.toLowerCase().includes(q);
      if (!inTitle && !inDesc && !inFull) return false;
    }
    if (category !== 'all' && n.category !== category) return false;
    if (priority !== 'all' && n.priority !== priority) return false;
    if (status !== 'all' && n.status !== status) return false;
    if (dateFrom && new Date(n.date) < new Date(dateFrom)) return false;
    if (dateTo && new Date(n.date) > new Date(dateTo)) return false;
    if (clientName && (!n.clientName || !n.clientName.toLowerCase().includes(clientName.toLowerCase()))) return false;
    if (tripRef && (!n.tripRef || !n.tripRef.toLowerCase().includes(tripRef.toLowerCase()))) return false;
    if (busRef && (!n.busRef || !n.busRef.toLowerCase().includes(busRef.toLowerCase()))) return false;
    if (bookingRef && (!n.bookingRef || !n.bookingRef.toLowerCase().includes(bookingRef.toLowerCase()))) return false;
    if (paymentRef && (!n.paymentRef || !n.paymentRef.toLowerCase().includes(paymentRef.toLowerCase()))) return false;
    if (branchRef && (!n.branchRef || !n.branchRef.toLowerCase().includes(branchRef.toLowerCase()))) return false;
    return true;
  });
}

export function sortNotifications(notifs, sortBy = 'newest') {
  const sorted = [...notifs];
  switch (sortBy) {
    case 'newest':
      sorted.sort((a, b) => new Date(b.date) - new Date(a.date));
      break;
    case 'oldest':
      sorted.sort((a, b) => new Date(a.date) - new Date(b.date));
      break;
    case 'priority_desc':
      sorted.sort((a, b) => priorityRank[a.priority] - priorityRank[b.priority] || new Date(b.date) - new Date(a.date));
      break;
    case 'priority_asc':
      sorted.sort((a, b) => priorityRank[b.priority] - priorityRank[a.priority] || new Date(a.date) - new Date(b.date));
      break;
    default:
      break;
  }
  return sorted;
}

